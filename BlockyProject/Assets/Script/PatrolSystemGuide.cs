// ENEMY PATROL SYSTEM SETUP GUIDE
// ================================
// 
// QUICK SETUP:
// 1. Select your enemy GameObject in the scene
// 2. Add the "EnemyPatrolSetup" component to your enemy
// 3. In the Inspector, adjust the "Patrol Distance" and offsets if needed
// 4. Click "Create Patrol Points" button
// 5. The patrol points will be created and automatically assigned
// 
// MANUAL SETUP:
// 1. Create two empty GameObjects in your scene
// 2. Position them where you want the enemy to patrol between
// 3. In your enemy's Inspector, assign these GameObjects to "Point A" and "Point B" fields
